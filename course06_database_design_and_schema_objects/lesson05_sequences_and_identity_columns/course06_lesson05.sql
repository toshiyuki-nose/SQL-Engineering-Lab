PROMPT === Step 05: Expected identity behavior tests ===
DECLARE
  l_rejected BOOLEAN := FALSE;
  l_count NUMBER;
BEGIN
  BEGIN
    EXECUTE IMMEDIATE q'[INSERT INTO c06l05_identity_always (book_id, title) VALUES (99, 'Not Allowed')]';
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE = -32795 THEN
      l_rejected := TRUE;
      DBMS_OUTPUT.PUT_LINE('PASS ALWAYS rejected explicit ID: ORA-32795');
    ELSE RAISE; END IF;
  END;
  IF NOT l_rejected THEN
    RAISE_APPLICATION_ERROR(-20051, 'FAIL: ALWAYS accepted explicit ID');
  END IF;

  l_rejected := FALSE;
  BEGIN
    EXECUTE IMMEDIATE q'[INSERT INTO c06l05_identity_default (book_id, title) VALUES (NULL, 'Not Allowed')]';
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE = -1400 THEN
      l_rejected := TRUE;
      DBMS_OUTPUT.PUT_LINE('PASS BY DEFAULT rejected explicit NULL: ORA-01400');
    ELSE RAISE; END IF;
  END;
  IF NOT l_rejected THEN
    RAISE_APPLICATION_ERROR(-20052, 'FAIL: BY DEFAULT accepted explicit NULL');
  END IF;

  SELECT COUNT(*) INTO l_count
  FROM c06l05_identity_on_null
  WHERE title = 'Null Generates Identifier' AND book_id IS NOT NULL;
  IF l_count = 1 THEN
    DBMS_OUTPUT.PUT_LINE('PASS BY DEFAULT ON NULL generated ID');
  ELSE
    RAISE_APPLICATION_ERROR(-20053, 'FAIL: ON NULL did not generate an ID');
  END IF;
END;
