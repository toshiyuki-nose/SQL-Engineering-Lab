PROMPT === Step 03: Create identity tables ===
CREATE TABLE c06l05_identity_always (
  book_id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  title VARCHAR2(100) NOT NULL
);
CREATE TABLE c06l05_identity_default (
  book_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR2(100) NOT NULL
);
CREATE TABLE c06l05_identity_on_null (
  book_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  title VARCHAR2(100) NOT NULL
);

